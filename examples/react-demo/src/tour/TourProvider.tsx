import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import type { ReactNode } from 'react';
import { TourContext } from './context';
import { TourOverlay } from './TourOverlay';
import { browserStorage, LAST_SEEN_KEY, MUTED_KEY, safeGet, safeSet } from './storage';
import type { TourStorage } from './storage';
import { basicSteps, decideAutoStart, DEFAULT_MAX_WHATS_NEW, latestWhatsNewSteps } from './versions';
import type { TourColors, TourFile, TourKind, TourStep, TourTheme } from './types';
import './tour.css';

interface TourProviderProps {
  tour: TourFile;
  /** The running app's version, e.g. "2.4.0". Drives the what's-new logic. */
  appVersion: string;
  /** Start automatically on launch (basic tour on first run, what's new after an update). */
  autoStart?: boolean;
  /** Runs before each step, e.g. to navigate to `step.route`. */
  onBeforeStep?: (step: TourStep) => void | Promise<void>;
  /** Light/dark look of the card. Defaults to following the OS setting. */
  theme?: TourTheme;
  /** Override the tour's colors to match the app. */
  colors?: TourColors;
  /** Narration audio per step: { [step.id]: url }. Generated by /tour-voice. Steps without audio stay silent. */
  voice?: Record<string, string>;
  /** Where to remember the last seen version and mute setting. Defaults to localStorage. */
  storage?: TourStorage;
  /** Most what's-new steps shown at once to a user who skipped several releases (newest win). */
  maxWhatsNewSteps?: number;
  children: ReactNode;
}

interface ActiveTour {
  kind: TourKind;
  steps: TourStep[];
  index: number;
}

interface ResolvedStep {
  step: TourStep;
  index: number;
  element: Element | null;
}

export function TourProvider({
  tour,
  appVersion,
  autoStart = true,
  onBeforeStep,
  theme = 'system',
  colors,
  voice,
  storage = browserStorage,
  maxWhatsNewSteps = DEFAULT_MAX_WHATS_NEW,
  children,
}: TourProviderProps) {
  const [active, setActive] = useState<ActiveTour | null>(null);
  const [resolved, setResolved] = useState<ResolvedStep | null>(null);
  const [muted, setMuted] = useState(false);
  const direction = useRef<1 | -1>(1);
  const loaded = useRef(false);

  // Keep the latest callback without re-running effects when the parent passes a new function.
  const beforeStep = useRef(onBeforeStep);
  useEffect(() => {
    beforeStep.current = onBeforeStep;
  }, [onBeforeStep]);

  const endTour = useCallback(() => {
    setActive(null);
    void safeSet(storage, LAST_SEEN_KEY, appVersion);
  }, [appVersion, storage]);

  const changeMuted = useCallback(
    (value: boolean) => {
      setMuted(value);
      void safeSet(storage, MUTED_KEY, String(value));
    },
    [storage],
  );

  const startTour = useCallback(
    (kind: TourKind = 'basic') => {
      const steps =
        kind === 'basic' ? basicSteps(tour.steps) : latestWhatsNewSteps(tour.steps, appVersion, maxWhatsNewSteps);
      direction.current = 1;
      if (steps.length > 0) setActive({ kind, steps, index: 0 });
    },
    [tour, appVersion, maxWhatsNewSteps],
  );

  const go = useCallback(
    (dir: 1 | -1) => {
      if (!active) return;
      direction.current = dir;
      const index = active.index + dir;
      if (index >= active.steps.length) endTour();
      else if (index >= 0) setActive({ ...active, index });
    },
    [active, endTour],
  );

  // Load what we remembered once per launch, then decide whether to start. Storage may be async
  // (a settings file read through Electron IPC). The ref guard stops React StrictMode from running it twice.
  useEffect(() => {
    if (loaded.current) return;
    loaded.current = true;
    void Promise.all([safeGet(storage, LAST_SEEN_KEY), safeGet(storage, MUTED_KEY)]).then(([lastSeen, savedMuted]) => {
      setMuted(savedMuted === 'true');
      if (!autoStart) return;
      const decision = decideAutoStart(tour.steps, lastSeen, appVersion, maxWhatsNewSteps);
      if (decision) setActive({ ...decision, index: 0 });
      else void safeSet(storage, LAST_SEEN_KEY, appVersion);
    });
  }, [autoStart, tour, appVersion, storage, maxWhatsNewSteps]);

  // When the step changes: run onBeforeStep, find its element, and skip it if the element is missing.
  useEffect(() => {
    if (!active) {
      setResolved(null);
      return;
    }
    const step = withInheritedRoute(active.steps, active.index);
    let cancelled = false;
    (async () => {
      await beforeStep.current?.(step);
      const element = step.target ? await waitForElement(step.target) : null;
      if (cancelled) return;
      if (step.target && !element) {
        console.warn(`[tour] Skipping step "${step.id}": no visible element with data-tour="${step.target}"`);
        go(active.index + direction.current < 0 ? 1 : direction.current);
        return;
      }
      setResolved({ step, index: active.index, element });
    })();
    return () => {
      cancelled = true;
    };
  }, [active, go]);

  // The version the What's new button replays: the newest one that has steps.
  const whatsNewVersion = useMemo(
    () => latestWhatsNewSteps(tour.steps, appVersion, maxWhatsNewSteps)[0]?.since ?? null,
    [tour, appVersion, maxWhatsNewSteps],
  );

  const value = useMemo(
    () => ({ startTour, isActive: active !== null, whatsNewVersion }),
    [startTour, active, whatsNewVersion],
  );

  return (
    <TourContext.Provider value={value}>
      {children}
      {active && resolved && (
        <TourOverlay
          step={resolved.step}
          element={resolved.element}
          index={resolved.index}
          total={active.steps.length}
          kind={active.kind}
          theme={theme}
          colors={colors}
          voiceSrc={voice?.[resolved.step.id]}
          muted={muted}
          onMutedChange={changeMuted}
          onNext={() => go(1)}
          onBack={() => go(-1)}
          onClose={endTour}
        />
      )}
    </TourContext.Provider>
  );
}

/**
 * A step without a route belongs to the same page as the step before it.
 * Without this, pressing Back from another page would look for elements on the wrong page.
 */
function withInheritedRoute(steps: TourStep[], index: number): TourStep {
  const step = steps[index];
  if (step.route) return step;
  for (let i = index - 1; i >= 0; i--) {
    const route = steps[i].route;
    if (route) return { ...step, route };
  }
  return step;
}

/** Waits briefly for the element to appear, e.g. after a route change renders a new screen. */
function waitForElement(target: string, timeoutMs = 1500): Promise<Element | null> {
  const selector = `[data-tour="${CSS.escape(target)}"]`;
  const start = performance.now();
  return new Promise((resolve) => {
    const check = () => {
      const el = document.querySelector(selector);
      const rect = el?.getBoundingClientRect();
      if (el && rect && rect.width > 0 && rect.height > 0) resolve(el);
      else if (performance.now() - start > timeoutMs) resolve(null);
      else requestAnimationFrame(check);
    };
    check();
  });
}
